// Generates src/domain/source-tax/zurich/tariff-2026.generated.ts from the ESTV file.
// Run: bun run gen:tariff

import {
	parseTariffFile,
	tariffFileToData,
} from "../src/domain/source-tax/estv/record.ts";

export const SOURCE_PATH = "sources/estv/tar26zh.txt";
export const OUTPUT_PATH =
	"src/domain/source-tax/zurich/tariff-2026.generated.ts";

/** Reads the ESTV file bytes as latin1 text. */
export function decodeSource(bytes: ArrayBuffer): string {
	return new TextDecoder("latin1").decode(bytes);
}

/** Renders the generated module. Pure and deterministic. */
export function render(text: string): string {
	const data = tariffFileToData(parseTariffFile(text));
	const codes = Object.keys(data.tables);
	const tableLines = Object.entries(data.tables).map(
		([code, rows]) => `\t\t${code}: ${JSON.stringify(rows)},`,
	);
	const record = (values: Readonly<Record<string, number>>): string =>
		Object.entries(values)
			.map(([key, value]) => `\t\t${key}: ${value},`)
			.join("\n");
	return [
		"// Generated by scripts/gen-tariff-data.ts from sources/estv/tar26zh.txt.",
		"// Do not edit. Run `bun run gen:tariff` to write this file again.",
		"",
		'import { type TariffFile, tariffFileFromData } from "../estv/record.ts";',
		"",
		"/** Every code of records 06 and 11, in file order. */",
		`export const ZH_2026_CODES = ${JSON.stringify(codes)} as const;`,
		"",
		"/** Each band is `[from, width, minTax, rate]` in Rappen and hundredths of a percent. */",
		"export const ZH_2026: TariffFile = tariffFileFromData({",
		`\tcanton: ${JSON.stringify(data.canton)},`,
		`\tvalidFrom: ${JSON.stringify(data.validFrom)},`,
		"\ttables: {",
		...tableLines,
		"\t},",
		"\tmedians: {",
		record(data.medians),
		"\t},",
		"\tfees: {",
		record(data.fees),
		"\t},",
		"});",
		"",
	].join("\n");
}

if (import.meta.main) {
	const text = decodeSource(await Bun.file(SOURCE_PATH).arrayBuffer());
	await Bun.write(OUTPUT_PATH, render(text));
	console.log(`wrote ${OUTPUT_PATH}`);
}
